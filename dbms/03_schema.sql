    price_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id INT NOT NULL,
    base_price DECIMAL(10,2) NOT NULL,
    discount_amount DECIMAL(10,2) DEFAULT 0.00,
