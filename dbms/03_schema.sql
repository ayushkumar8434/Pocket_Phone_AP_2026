        REFERENCES Phone_Models(model_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT chk_camera_type CHECK (camera_type IN
        ('front', 'rear_primary', 'rear_secondary', 'rear_tertiary', 'rear_quaternary')),
    CONSTRAINT chk_megapixels CHECK (megapixels > 0),
    CONSTRAINT chk_aperture CHECK (aperture > 0)
);
CREATE INDEX idx_model_camera ON Camera_Specs (model_id, camera_type);

