-- Trigger: mark the listing sold when a transaction payment is completed
CREATE OR REPLACE FUNCTION fn_update_listing_status_after_transaction()
RETURNS trigger AS $$
BEGIN
    IF NEW.payment_status = 'completed' AND OLD.payment_status <> 'completed' THEN
        UPDATE Phone_Listings
        SET status = 'sold'
        WHERE listing_id = NEW.listing_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_update_listing_status_after_transaction
AFTER UPDATE ON Transactions
FOR EACH ROW
EXECUTE FUNCTION fn_update_listing_status_after_transaction();

-- Trigger: ensure only one current price per listing
CREATE OR REPLACE FUNCTION fn_set_old_prices_non_current()
RETURNS trigger AS $$
BEGIN
    IF NEW.is_current THEN
        UPDATE Pricing
        SET is_current = FALSE
        WHERE listing_id = NEW.listing_id AND is_current;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_set_old_prices_non_current
BEFORE INSERT ON Pricing
FOR EACH ROW
EXECUTE FUNCTION fn_set_old_prices_non_current();

-- Trigger: calculate final price if not provided
CREATE OR REPLACE FUNCTION fn_calculate_final_price()
RETURNS trigger AS $$
BEGIN
    IF NEW.final_price IS NULL OR NEW.final_price = 0 THEN
        NEW.final_price := NEW.base_price - COALESCE(NEW.discount_amount, 0);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_calculate_final_price
BEFORE INSERT ON Pricing
FOR EACH ROW
EXECUTE FUNCTION fn_calculate_final_price();

