-- Function: create a new listing together with its price. Returns the listing_id.
CREATE OR REPLACE FUNCTION create_listing(
    p_model_id INT,
    p_seller_id INT,
    p_storage_capacity INT,
    p_ram INT,
    p_color VARCHAR,
    p_condition VARCHAR,
    p_base_price NUMERIC,
    p_discount_amount NUMERIC,
    p_description TEXT,
    p_listing_type VARCHAR
) RETURNS INT AS $$
DECLARE
    v_listing_id INT;
    v_final_price NUMERIC(10,2);
BEGIN
    v_final_price := p_base_price - COALESCE(p_discount_amount, 0);

    INSERT INTO Phone_Listings (
        model_id, seller_id, storage_capacity, ram, color,
        condition, listing_type, description
    ) VALUES (
        p_model_id, p_seller_id, p_storage_capacity, p_ram, p_color,
        p_condition, p_listing_type, p_description
    ) RETURNING listing_id INTO v_listing_id;

    INSERT INTO Pricing (
        listing_id, base_price, discount_amount, final_price, is_current
    ) VALUES (
        v_listing_id, p_base_price, COALESCE(p_discount_amount, 0), v_final_price, TRUE
    );

    RETURN v_listing_id;
END;
$$ LANGUAGE plpgsql;

-- Function: reserve a listing and create its transaction and shipping rows.
-- Returns the new transaction_id (NULL when the purchase is refused) and a message.
CREATE OR REPLACE FUNCTION process_transaction(
    p_listing_id INT,
    p_buyer_id INT,
    p_payment_method VARCHAR,
    p_shipping_address TEXT,
    p_city_id INT,
    p_pincode VARCHAR,
    OUT o_transaction_id INT,
    OUT o_message TEXT
) AS $$
DECLARE
    v_listing_status VARCHAR(10);
    v_final_price NUMERIC(10,2);
    v_seller_id INT;
BEGIN
    SELECT status, seller_id INTO v_listing_status, v_seller_id
    FROM Phone_Listings
    WHERE listing_id = p_listing_id
    FOR UPDATE;

    IF v_listing_status IS DISTINCT FROM 'available' THEN
        o_message := 'Listing is not available';
        o_transaction_id := NULL;
    ELSIF v_seller_id = p_buyer_id THEN
        o_message := 'Cannot buy your own listing';
        o_transaction_id := NULL;
    ELSE
        SELECT final_price INTO v_final_price
        FROM Pricing
        WHERE listing_id = p_listing_id AND is_current = TRUE;

        INSERT INTO Transactions (listing_id, buyer_id, amount, payment_method)
        VALUES (p_listing_id, p_buyer_id, v_final_price, p_payment_method)
        RETURNING transaction_id INTO o_transaction_id;

        INSERT INTO Shipping_Details (transaction_id, street_address, city_id, pincode)
        VALUES (o_transaction_id, p_shipping_address, p_city_id, p_pincode);

        UPDATE Phone_Listings SET status = 'reserved' WHERE listing_id = p_listing_id;

        o_message := 'Transaction created successfully';
    END IF;
END;
$$ LANGUAGE plpgsql;

