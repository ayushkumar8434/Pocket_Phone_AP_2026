-- States Table
CREATE TABLE States (
    state_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_name VARCHAR(100) NOT NULL,
    country VARCHAR(100) NOT NULL DEFAULT 'India',
    CONSTRAINT uk_state_name UNIQUE (state_name, country)
);

-- Cities Table
CREATE TABLE Cities (
    city_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(100) NOT NULL,
    state_id INT NOT NULL,
    CONSTRAINT fk_cities_state FOREIGN KEY (state_id)
        REFERENCES States(state_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT uk_city_state UNIQUE (city_name, state_id)
);
CREATE INDEX idx_cities_state ON Cities (state_id);

