        REFERENCES Users(user_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT chk_condition CHECK (condition IN ('new', 'like_new', 'good', 'fair', 'poor')),
    CONSTRAINT chk_status CHECK (status IN ('available', 'sold', 'reserved', 'removed')),
    CONSTRAINT chk_listing_type CHECK (listing_type IN
        ('regular', 'popular', 'todays_drop', 'good_deal', 'featured')),
    CONSTRAINT chk_storage CHECK (storage_capacity > 0),
