-- Brands Table
CREATE TABLE Brands (
    brand_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name VARCHAR(100) NOT NULL UNIQUE,
    brand_logo VARCHAR(255),
    description TEXT,
    country_of_origin VARCHAR(100),
    is_active BOOLEAN DEFAULT TRUE
);

-- Phone Models Table
CREATE TABLE Phone_Models (
    model_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id INT NOT NULL,
    model_name VARCHAR(150) NOT NULL,
    release_year INT,
    display_size DECIMAL(4,2), -- in inches
    processor VARCHAR(100),
    os_version VARCHAR(50),
    battery_capacity INT, -- in mAh
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_models_brand FOREIGN KEY (brand_id)
        REFERENCES Brands(brand_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT uk_brand_model UNIQUE (brand_id, model_name),
    CONSTRAINT chk_release_year CHECK (release_year >= 2000 AND release_year <= 2100),
    CONSTRAINT chk_display_size CHECK (display_size > 0),
    CONSTRAINT chk_battery CHECK (battery_capacity > 0)
);
CREATE INDEX idx_model_name ON Phone_Models (model_name);
CREATE INDEX idx_release_year ON Phone_Models (release_year);
-- Trigram index for LIKE '%text%' model search
